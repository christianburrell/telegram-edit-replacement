def run_suite(cwd, rel=None):
    """(last line of the runner's report, tests run); ("TIMEOUT", None) when it hangs."""
    try:
        r = subprocess.run(SUITES.get(rel, SUITE), cwd=cwd, capture_output=True, text=True, timeout=TIMEOUT_S,
                           env=OFFLINE_ENV)
    except subprocess.TimeoutExpired:
        return "TIMEOUT", None
    ran = re.findall(r"^Ran (\d+) tests?", r.stderr, re.M)           # the OUTER runner reports last
    lines = r.stderr.strip().splitlines()
    return (lines[-1] if lines else ""), (int(ran[-1]) if ran else None)


def drifted():
    """Entries that would not test their rule: text that no longer occurs exactly once (an unmutated
    copy), an indented pattern matching inside a more-indented line (code moved one block deeper), or a
    mutant that no longer parses. The last two are "killed" by any test that loads the file, for the
    wrong reason. A pattern starting with one space is a deliberate mid-line fragment."""
    bad = []
    for name, rel, old, new in CATALOG:
        text = (ROOT / rel).read_text()
        hits = text.count(old)
        if hits != 1:
            bad.append((name, f"{hits} matches"))
            continue
        at = text.index(old)
        if old.startswith("  ") and at and text[at - 1] != "\n":
            bad.append((name, "indented pattern matches mid-line"))
            continue
        mutated = text.replace(old, new, 1)
        if rel.endswith(".py"):
            try:
                compile(mutated, rel, "exec")
            except SyntaxError as exc:
                bad.append((name, f"mutant does not parse (line {exc.lineno})"))
        elif rel.endswith(".sh"):
            parsed = subprocess.run(["bash", "-n"], input=mutated, capture_output=True, text=True)
            if parsed.returncode:
                bad.append((name, "mutant does not parse: " + parsed.stderr.strip()[:80]))
    return bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=2, help="no more than cores and free memory allow")
    ap.add_argument("--check", action="store_true", help="only validate the patterns")
    ap.add_argument("--only", default="", help="comma-separated mutant names: re-check survivors after adding "
                    "tests; any change to the plugin needs the whole catalog")
    args = ap.parse_args()
    names = [entry[0] for entry in CATALOG]
    if len(set(names)) != len(names):
        print("duplicate mutant names")
        return 2
    if any("," in name for name in names):      # --only takes a comma-separated list
        print("mutant names with a comma:", [name for name in names if "," in name])
        return 2
    bad = drifted()
    if bad:
        print("patterns that would not test their rule:", bad)
        return 2
    if args.check:
        print(f"{len(CATALOG)} patterns OK")
        return 0
    if importlib.util.find_spec("telegram") is None:
        print("run this with the Hermes interpreter: the pipeline tests would be skipped")
        return 2
    chosen = [entry for entry in CATALOG if not args.only or entry[0] in args.only.split(",")]
    if args.only and len(chosen) != len(set(args.only.split(","))):
        print("unknown mutant names in --only")
        return 2
    bases = {}
    for rel in sorted({SUITES.get(entry[1]) and entry[1] for entry in chosen}, key=str):
        last, count = run_suite(ROOT, rel)
        if not last.startswith("OK") or count is None or "skipped" in last:
            print("baseline is not green:", rel or "full suite", last)
            return 2
        bases[rel] = count
        print(f"baseline: {rel or 'full suite'}: {last} ({count} tests)", flush=True)
    print(f"{len(chosen)} mutants", flush=True)
    tmp = tempfile.mkdtemp(prefix="mutants-", dir=os.environ.get("TMPDIR"))

    def one(job):
        i, (name, rel, old, new) = job
        copy = Path(tmp) / f"m{i:03d}"
        shutil.copytree(ROOT, copy, ignore=IGNORE)
        target = copy / rel
        target.write_text(target.read_text().replace(old, new, 1))
        suite = rel if rel in SUITES else None
        result, ran = run_suite(copy, suite)
        shutil.rmtree(copy, ignore_errors=True)
        # killed: the suite hung, or failed with the full test count (an import error "fails" with fewer)
        killed = result == "TIMEOUT" or (result.startswith("FAILED") and ran == bases[suite])
        print(f"{'killed  ' if killed else 'SURVIVED'} {name}: {result}", flush=True)
        return name, killed, result, ran

    try:
        with ThreadPoolExecutor(max_workers=args.workers) as pool:
            results = list(pool.map(one, enumerate(chosen)))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)    # skipped if the process is killed: clean $TMPDIR/mutants-*
    survivors = [(name, result, ran) for name, killed, result, ran in results if not killed]
    for name, result, ran in survivors:
        print(f"SURVIVED: {name}: {result} (ran {ran})")
    print(f"{len(chosen) - len(survivors)}/{len(chosen)} mutants killed")
    return 1 if survivors else 0


if __name__ == "__main__":
    raise SystemExit(main())
